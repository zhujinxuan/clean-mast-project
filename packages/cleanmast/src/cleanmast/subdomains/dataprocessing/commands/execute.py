"""Execute command for wt_timeseries.

This module provides the CLI command for executing wt-timeseries processing
from configuration file.

ADR-GUARDRAILS: structure-001-subdomain-layout, cli-001-click-cli-patterns
Compliance: Subdomain layout ✓ | CLI Pattern ✓ | Command Implementation ✓
"""

from pathlib import Path

import click

from cleanmast.subdomains.configuration.value_objects.wt_timeseries_config import (
    load_wt_timeseries_config,
)
from cleanmast.subdomains.dataprocessing.services.wt_timeseries_generator import (
    process_single_mast_csv,
)
from cleanmast.subdomains.dataprocessing.services.turbulence_calculator import (
    process_turbulence_for_mast,
)


def execute_wt_timeseries(config_path: Path) -> None:
    """Execute wt-timeseries processing from config file.

    1. Load and validate wt-timeseries.toml
    2. For each mast:
       - Call process_single_mast_csv() from wt_timeseries_generator
       - Call process_turbulence_for_mast() from turbulence_calculator
    3. Print progress output

    Args:
        config_path: Path to wt-timeseries.toml configuration file

    Raises:
        FileNotFoundError: If config file doesn't exist
        ValueError: If configuration is invalid
    """
    # Load configuration
    config = load_wt_timeseries_config(config_path)
    project_dir = config_path.parent

    click.echo(f"Loaded configuration from: {config_path}")
    click.echo(f"Processing {len(config.masts)} mast(s)...")

    for mast in config.masts:
        click.echo(f"\nProcessing mast: {mast.name}")

        # Generate CSV file
        click.echo(f"  Generating CSV with {len(mast.csv_heights)} height(s)...")
        process_single_mast_csv(mast, project_dir)

        # Generate turbulence files
        if mast.turbulence_heights:
            click.echo(f"  Generating turbulence files for {len(mast.turbulence_heights)} height(s)...")
            process_turbulence_for_mast(mast, project_dir)
        else:
            click.echo(f"  No turbulence heights configured, skipping...")

    click.echo("\nProcessing complete!")
    click.echo(f"Output directory: {project_dir / 'wt-timeseries'}")


@click.command("wt-timeseries")
@click.argument("config_path", type=click.Path(exists=True))
def execute_wt_timeseries_cli(config_path):
    """Execute wt-timeseries processing from configuration file.

    This command:
    1. Loads the specified wt-timeseries.toml configuration file
    2. For each mast:
       - Generates CSV file with wind speed/direction at CSV heights
       - Generates turbulence intensity files at turbulence heights
    3. Prints progress output

    Prerequisites:
    - Configuration file must exist (generated by recommend command)

    Outputs:
    - wt-timeseries/*.csv: CSV files for each mast
    - wt-timeseries/turbulence-*/meteodyn_ti_*.txt: Turbulence files

    Examples:
        uv run cleanmast wt-timeseries path/to/wt-timeseries.toml
    """
    config_path_obj = Path(config_path)

    try:
        execute_wt_timeseries(config_path_obj)
    except FileNotFoundError as e:
        raise click.ClickException(f"File not found: {e}")
    except ValueError as e:
        raise click.ClickException(f"Configuration error: {e}")
