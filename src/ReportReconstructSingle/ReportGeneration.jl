"""
    generate_reconstruction_report(config::AnalyzeReconstructSingleConfig, results::Dict{String, Any})

Generate a comprehensive Typst report for reconstruction analysis.
"""
function generate_reconstruction_report(config::AnalyzeReconstructSingleConfig, results::Dict{String, Any})::String
    report_path = joinpath(config.outputDir, "reconstruction_analysis_report.typ")
    
    open(report_path, "w") do io
        # Write document header
        write(io, """
        // Reconstruction Analysis Report
        // Generated by CleanMastProject.jl
        // Date: $(Dates.format(now(), "yyyy-mm-dd HH:MM:SS"))
        
        #set document(
          title: "重构前后数据对比分析报告",
          author: "CleanMastProject Analysis System",
        )
        
        #set page(
          paper: "a4",
          margin: (x: 2cm, y: 2.5cm),
          numbering: "1",
          number-align: center,
        )
        
        #set heading(numbering: "1.")
        
        #set par(justify: true)
        
        // Title page
        #align(center)[
          #v(5cm)
          #text(size: 24pt, weight: "bold")[重构前后数据对比分析报告]
          
          #v(1cm)
          
          #text(size: 18pt)[Reconstruction Data Comparison Analysis Report]
          
          #v(2cm)
          
          #text(size: 14pt)[
            分析测风塔数量: $(length(config.masts))
          ]
          
          #v(4cm)
          
          #text(size: 12pt)[
            生成日期: #datetime.today().display("[year]年[month]月[day]日")
          ]
        ]
        
        #pagebreak()
        
        // Table of contents
        #outline(
          title: [目录 / Table of Contents],
          indent: 1em,
          depth: 3,
        )
        
        #pagebreak()
        
        // Executive summary
        = 执行摘要 / Executive Summary
        
        本报告对测风塔数据重构前后的结果进行了综合对比分析，主要包括：
        
        - 数据缺失率和重构率分析
        - 不同高度间风速相关性分析（R²矩阵）
        - 不同高度间风向差异分析
        
        """)
        
        # Process each mast
        for (idx, mast) in enumerate(config.masts)
            mast_results = results[mast.name]
            
            write(io, """
            
            #pagebreak()
            
            = 测风塔 $(mast.name) 分析结果
            
            """)
            
            # Data coverage section
            write_data_coverage_section(io, mast.name, mast_results["coverage"])
            
            # Wind speed correlation section
            write_wind_speed_correlation_section(io, mast.name, mast_results["speed_correlation"], config.outputDir)
            
            # Wind direction difference section
            write_wind_direction_difference_section(io, mast.name, mast_results["direction_difference"])
        end
    end
    
    @info "Typst report generated at: $report_path"
    return report_path
end

"""
    write_data_coverage_section(io::IO, mast_name::String, coverage_results::Dict)

Write the data coverage analysis section to the report.
"""
function write_data_coverage_section(io::IO, mast_name::String, coverage_results::Dict)
    write(io, """
    
    == 数据覆盖率分析
    
    本节分析重构前后的数据缺失情况和重构效果。
    
    === 整体统计
    
    - 传感器总数: $(coverage_results["summary"]["total_sensors"])
    - 平均重构率: $(round(coverage_results["summary"]["avg_reconstruction_rate"], digits=2))%
    - 重构后平均数据覆盖率: $(round(coverage_results["summary"]["avg_coverage_after"], digits=2))%
    
    === 传感器重构统计
    
    """)
    
    # Create combined wind speed and wind direction table using functional programming
    wind_speed_stats = coverage_results["wind_speed_stats"]
    wind_dir_stats = coverage_results["wind_direction_stats"]
    
    combined_stats = []
    
    # Add wind speed sensors
    if !isempty(wind_speed_stats)
        ws_data = wind_speed_stats |>
                 (stats -> map(s -> (
                     sensor_type = "风速",
                     height = s.height,
                     missing_before = s.missingBefore,
                     missing_after = s.missingAfter,
                     reconstruction_rate = round(s.reconstructionRate, digits=2),
                     coverage_after = round(s.coverageRatioAfter, digits=2)
                 ), stats))
        append!(combined_stats, ws_data)
    end
    
    # Add wind direction sensors  
    if !isempty(wind_dir_stats)
        wd_data = wind_dir_stats |>
                 (stats -> map(s -> (
                     sensor_type = "风向",
                     height = s.height,
                     missing_before = s.missingBefore,
                     missing_after = s.missingAfter,
                     reconstruction_rate = round(s.reconstructionRate, digits=2),
                     coverage_after = round(s.coverageRatioAfter, digits=2)
                 ), stats))
        append!(combined_stats, wd_data)
    end
    
    if !isempty(combined_stats)
        # Create combined DataFrame and sort by sensor type then height
        combined_df = DataFrame(combined_stats) |>
                     (df -> sort(df, [:sensor_type, :height], rev=[false, true])) |>
                     (df -> transform(df, :sensor_type => (types -> map(t -> t == "风速" ? t : t, types)) => :sensor_type)) |>
                     (df -> transform(df, [:sensor_type, :height] => ((types, heights) -> map((t, h) -> "$(t) $(h)m", types, heights)) => :数据类型)) |>
                     (df -> select(df, :数据类型, :missing_before, :missing_after, :reconstruction_rate, :coverage_after)) |>
                     (df -> rename(df,
                         :missing_before => "重构前缺失点数",
                         :missing_after => "重构后缺失点数", 
                         :reconstruction_rate => "重构率(%)",
                         :coverage_after => "重构后覆盖率(%)"
                     ))
        
        combined_table = simple_table(combined_df)
        write(io, "表格：测风塔$(mast_name)传感器重构统计\n\n")
        show(io, MIME"text/typst"(), combined_table)
        write(io, "\n\n")
    end
end

"""
    write_wind_speed_correlation_section(io::IO, mast_name::String, speed_results::Dict, output_dir::String)

Write the wind speed correlation analysis section to the report.
"""
function write_wind_speed_correlation_section(io::IO, mast_name::String, speed_results::Dict, output_dir::String)
    write(io, """
    
    == 风速相关性分析
    
    本节分析重构后不同高度间风速的相关性（R²值）。
    
    === 风速R²矩阵
    
    """)
    
    # Create R² matrix table using functional programming
    r2_df = speed_results["r2_df"]
    if !isnothing(r2_df) && !isempty(r2_df)
        # Format the DataFrame for display using functional composition
        numeric_cols = names(r2_df) |> (cols -> filter(col -> col != :height, cols))
        transformations = map(numeric_cols) do col
            col => (values -> map(v -> isnan(v) ? "-" : string(round(v, digits=3)), values)) => col
        end
        
        display_df = copy(r2_df) |>
                    (df -> transform(df, transformations...)) |>
                    (df -> rename(df, :height => "高度(m)"))
        
        r2_table = simple_table(display_df)
        write(io, "表格：测风塔$(mast_name)风速R²相关系数矩阵\n\n")
        show(io, MIME"text/typst"(), r2_table)
        write(io, "\n\n")
    end
    
    # Add correlation plots
    write(io, """
    === 风速相关性散点图
    
    以下图表展示了不同高度组合间的风速相关性，包含散点图、线性回归线和R²值。
    
    """)
    
    # Add plot references
    plots = speed_results["plots"]
    if haskey(plots, "high_vs_high") && !isnothing(plots["high_vs_high"])
        plot_info = plots["high_vs_high"]
        plot_path = isa(plot_info, Dict) ? plot_info["plot"] : plot_info
        rel_path = relpath(plot_path, output_dir)
        rel_path = replace(rel_path, "\\" => "/")
        write(io, """
        #figure(
          image("$(rel_path)", width: 100%),
          caption: [高层（≥100m）风速相互关系]
        )
        
        """)
    end
    
    if haskey(plots, "high_vs_low") && !isnothing(plots["high_vs_low"])
        plot_info = plots["high_vs_low"]
        plot_path = isa(plot_info, Dict) ? plot_info["plot"] : plot_info
        rel_path = relpath(plot_path, output_dir)
        rel_path = replace(rel_path, "\\" => "/")
        write(io, """
        #figure(
          image("$(rel_path)", width: 100%),
          caption: [高层（≥100m）与低层（\\<100m）风速关系]
        )
        
        """)
    end
    
    if haskey(plots, "low_vs_low") && !isnothing(plots["low_vs_low"])
        plot_info = plots["low_vs_low"]
        plot_path = isa(plot_info, Dict) ? plot_info["plot"] : plot_info
        rel_path = relpath(plot_path, output_dir)
        rel_path = replace(rel_path, "\\" => "/")
        write(io, """
        #figure(
          image("$(rel_path)", width: 100%),
          caption: [低层（\\<100m）风速相互关系]
        )
        
        """)
    end
end

"""
    write_wind_direction_difference_section(io::IO, mast_name::String, direction_results::Dict)

Write the wind direction difference analysis section to the report.
"""
function write_wind_direction_difference_section(io::IO, mast_name::String, direction_results::Dict)
    write(io, """
    
    == 风向差异分析
    
    本节分析重构后不同高度间风向的差异，包括平均差异和标准差。
    
    === 风向平均差异矩阵
    
    矩阵中的值表示行高度减去列高度的平均风向差（单位：度）。
    
    """)
    
    # Create mean difference table using functional programming
    mean_df = direction_results["mean_df"]
    if !isnothing(mean_df) && !isempty(mean_df)
        # Format the DataFrame for display using functional composition
        numeric_cols = names(mean_df) |> (cols -> filter(col -> col != :from_height, cols))
        transformations = map(numeric_cols) do col
            col => (values -> map(v -> isnan(v) ? "-" : string(round(v, digits=2)), values)) => col
        end
        
        display_df = copy(mean_df) |>
                    (df -> transform(df, transformations...)) |>
                    (df -> rename(df, :from_height => "高度(m)"))
        
        mean_table = simple_table(display_df)
        write(io, "表格：测风塔$(mast_name)风向平均差异矩阵（度）\n\n")
        show(io, MIME"text/typst"(), mean_table)
        write(io, "\n\n")
    end
    
    write(io, """
    === 风向差异标准差矩阵
    
    矩阵中的值表示不同高度间风向差异的标准差（单位：度）。
    
    """)
    
    # Create std difference table using functional programming
    std_df = direction_results["std_df"]
    if !isnothing(std_df) && !isempty(std_df)
        # Format the DataFrame for display using functional composition
        numeric_cols = names(std_df) |> (cols -> filter(col -> col != :from_height, cols))
        transformations = map(numeric_cols) do col
            col => (values -> map(v -> isnan(v) ? "-" : string(round(v, digits=2)), values)) => col
        end
        
        display_df = copy(std_df) |>
                    (df -> transform(df, transformations...)) |>
                    (df -> rename(df, :from_height => "高度(m)"))
        
        std_table = simple_table(display_df)
        write(io, "表格：测风塔$(mast_name)风向差异标准差矩阵（度）\n\n")
        show(io, MIME"text/typst"(), std_table)
        write(io, "\n\n")
    end
    
    # Add summary statistics
    summary = direction_results["summary"]
    write(io, """
    === 风向差异汇总统计
    
    - 平均风向差异的均值: $(round(summary["avg_mean_difference"], digits=2))°
    - 风向差异标准差的均值: $(round(summary["avg_std_difference"], digits=2))°
    - 最大平均风向差异: $(round(summary["max_mean_difference"], digits=2))°
    - 最大风向差异标准差: $(round(summary["max_std_difference"], digits=2))°
    
    """)
end

